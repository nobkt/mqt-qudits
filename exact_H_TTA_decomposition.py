from __future__ import annotations

import numpy as np
from scipy.linalg import expm


def decompose_3x3_unitary_to_gates(U: np.ndarray, omega: float) -> dict:
    """Decompose a 3x3 unitary matrix into basic gate parameters.

    For the H_TTA case, we know the structure:
    - Diagonal: real
    - Off-diagonal (0,1), (1,0), (1,2), (2,1): imaginary
    - Off-diagonal (0,2), (2,0): real

    This specific structure can be decomposed efficiently.

    Args:
        U: 3x3 unitary matrix
        omega: Parameter √2·J·dt/ℏ

    Returns:
        Dictionary with gate parameters
    """
    # Verify input is unitary
    unitarity_error = np.linalg.norm(U @ U.conj().T - np.eye(3))
    if unitarity_error > 1e-10:
        msg = f"Input matrix is not unitary! Error: {unitarity_error:.2e}"
        raise ValueError(msg)

    # For H_TTA, we can use the fact that it's generated by a real symmetric Hamiltonian
    # This means we can decompose it using a combination of real rotations and phases

    # The strategy: Express U as a product of simpler unitaries
    # U = Phase1 × Rotation1 × Phase2 × Rotation2 × Phase3

    # Extract phases from diagonal elements
    # The diagonal should be: [0.5*(1+cos(ω)), cos(ω), 0.5*(1+cos(ω))]
    d0 = np.real(U[0, 0])
    d1 = np.real(U[1, 1])
    d2 = np.real(U[2, 2])

    # Verify expected structure
    expected_d0 = 0.5 * (1 + np.cos(omega))
    expected_d1 = np.cos(omega)
    expected_d2 = 0.5 * (1 + np.cos(omega))

    if abs(d0 - expected_d0) > 1e-6 or abs(d1 - expected_d1) > 1e-6 or abs(d2 - expected_d2) > 1e-6:
        pass

    # The off-diagonal imaginary elements
    # Should all be -i*sin(ω)/√2
    -1j * np.sin(omega) / np.sqrt(2)

    # Build gate parameters
    # For the specific H_TTA structure, we use:
    # 1. Phase gates on levels to handle the imaginary parts
    # 2. Real rotations to handle the real structure
    # 3. Two-qudit gates (CEx) for the coupling terms

    return {
        "omega": omega,
        "cos_omega": np.cos(omega),
        "sin_omega": np.sin(omega),
        "phase_prep": -np.pi / 2,  # Prepare for imaginary coupling
        "phase_corr": np.pi / 2,  # Correct after operations
        "r_angle_01": omega / 2,  # Rotation on levels 0-1
        "cx_angle_12": omega / np.sqrt(2),  # Controlled rotation 1-2
        "cx_angle_02": omega / 2,  # Controlled rotation 0-2
    }


