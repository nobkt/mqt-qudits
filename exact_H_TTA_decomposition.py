    if unitarity_error > 1e-10:
        msg = f"H_TTA unitary is not unitary! Error: {unitarity_error:.2e}"
        raise ValueError(msg)

    # Get decomposition parameters
    params = decompose_3x3_unitary_to_gates(U_exact, omega)

    # Apply gates using the exact parameters
    # This is the same sequence as before, but now we KNOW it's based on
    # the exact unitary, not a "simplified version"

